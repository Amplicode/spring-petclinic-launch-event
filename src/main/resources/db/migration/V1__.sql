CREATE TABLE owners (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   first_name VARCHAR,
   last_name VARCHAR,
   address VARCHAR,
   city VARCHAR,
   telephone VARCHAR,
   CONSTRAINT pk_owners PRIMARY KEY (id)
);

CREATE TABLE pets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   name VARCHAR,
   birth_date date,
   type_id INTEGER,
   owner_id INTEGER,
   CONSTRAINT pk_pets PRIMARY KEY (id)
);

CREATE TABLE specialties (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   name VARCHAR,
   CONSTRAINT pk_specialties PRIMARY KEY (id)
);

CREATE TABLE types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   name VARCHAR,
   CONSTRAINT pk_types PRIMARY KEY (id)
);

CREATE TABLE vet_specialties (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   specialty_id INTEGER,
   vet_id INTEGER,
   CONSTRAINT pk_vet_specialties PRIMARY KEY (id)
);

CREATE TABLE vets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   first_name VARCHAR,
   last_name VARCHAR,
   CONSTRAINT pk_vets PRIMARY KEY (id)
);

CREATE TABLE visits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   visit_date date,
   description VARCHAR,
   pet_id INTEGER,
   CONSTRAINT pk_visits PRIMARY KEY (id)
);

